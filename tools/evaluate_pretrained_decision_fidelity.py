def plain(value):
    if torch.is_tensor(value):
        return plain(value.detach().cpu().tolist())
    if isinstance(value, np.ndarray):
        return plain(value.tolist())
    if isinstance(value, np.generic):
        return plain(value.item())
    if isinstance(value, float) and not math.isfinite(value):
        return {'__nonfinite_float__': repr(value)}
    if isinstance(value, dict):
        return {str(k): plain(v) for k, v in value.items()}
    if isinstance(value, (set, frozenset)):
        return sorted(plain(v) for v in value)
    if isinstance(value, (tuple, list)):
        return [plain(v) for v in value]
    if hasattr(value, '__dataclass_fields__'):
        return plain(asdict(value))
    return value


def fingerprint(value):
    return hashlib.sha256(json.dumps(plain(value), sort_keys=True,
        separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def validate_pretrained(campaign):
    path = Path(campaign)/'snapshot/checkpoints/latest.pt'
    if sha256(path) != PRETRAINED_SHA256:
        raise ValueError('decision fidelity requires the frozen complete pretrained Prior+FM checkpoint')
    campaign_protocol = json.loads((Path(campaign)/'protocol.json').read_text())
    if (campaign_protocol['checkpoint_sha256'] != PRETRAINED_SHA256 or
            sha256(Path(campaign)/'snapshot/run_config.toml') != campaign_protocol['config_sha256']):
        raise ValueError('frozen pretrained campaign configuration identity differs')
    payload = torch.load(path, map_location='cpu', weights_only=True)
    state, metrics = payload['training_state'], payload['training_state']['metrics']
    if (payload['phase'] != 'online_training' or payload['next_unit'] != 0
            or metrics['world_model_initialization_updates'] != 49636
            or metrics['online_episodes_completed'] != 0 or state['next_environment_episode'] != 0
            or state['replay']['online']['episodes']):
        raise ValueError('pretrained checkpoint must have 49636 initialization updates and no online learning')
    return dict(checkpoint=str(path.resolve()), checkpoint_sha256=PRETRAINED_SHA256,
        initialization_updates=49636, online_episodes=0, predictor='pretrained_graph_prior_fm')


class CausalShortestController:
    """The same observed-speed shortest-path rule in real and model branches."""
    def __init__(self, network, candidates, max_speed):
        self.network, self.candidates, self.max_speed = network, candidates, max_speed
        self.router = RealTimeShortestRouter(network)

    def prepare(self, flow, now):
        speeds = clip_road_speed_fractions(np.asarray(flow)[:, 1], 'meso') * self.network.speed_limits_mps
        speeds = np.minimum(speeds, self.max_speed)
        self.router.update_costs(self.network.lengths_m / np.maximum(speeds, .1), now)

    def __call__(self, pending, flow, now):
        return [NextHopDecision(str(row['vehicle_id']), int(row['current_edge']),
            self.router.next_edge(int(row['current_edge']), int(row['destination_edge']),
                self.candidates.candidates(int(row['current_edge']), int(row['destination_edge']))), float(now))
            for row in pending]

    def state_dict(self):
        return copy.deepcopy({key: getattr(self.router, key) for key in CONTROLLER_FIELDS})

    def load_state_dict(self, state):
        if set(state) != set(CONTROLLER_FIELDS):
            raise ValueError('controller state schema differs')
        for key, value in copy.deepcopy(state).items():
            setattr(self.router, key, value)


def external_rng_state():
    return dict(python=random.getstate(), numpy=np.random.get_state(), torch=torch.get_rng_state().clone())


def restore_external_rng(state):
    random.setstate(state['python'])
    np.random.set_state(state['numpy'])
    torch.set_rng_state(state['torch'])


def causal_state(session, controller):
    values = copy.deepcopy({key: getattr(session, key) for key in SESSION_FIELDS})
    values['metrics'].pop('wall_seconds', None)
    policy = controller.state_dict()
    policy['stats'].pop('optimize_seconds', None)
    return dict(session=values, controller=policy, external_rng=external_rng_state())


def simulator_observation(session):
    """Read directly, bypassing the wrapper's frozen flow cache."""
    api = session._connection
    vehicles = {}
    for name in sorted(api.vehicle.getIDList()):
        vehicles[name] = dict(road=api.vehicle.getRoadID(name), position=api.vehicle.getLanePosition(name),
            speed=api.vehicle.getSpeed(name), route=tuple(api.vehicle.getRoute(name)),
            route_index=api.vehicle.getRouteIndex(name), departure=api.vehicle.getDeparture(name))
        if name not in session._vehicles:
            raise ValueError('unregistered vehicle present in SUMO')
        session._route_commitment(name, route_index=vehicles[name]['route_index'])
    registered, missing = {}, []
    for name, row in sorted(session._vehicles.items()):
        if row['arrived']:
            continue
        try:
            registered[name] = tuple(api.vehicle.getRoute(name))
        except Exception:
            missing.append(name)
    lights = {name: dict(state=api.trafficlight.getRedYellowGreenState(name),
        phase=api.trafficlight.getPhase(name), program=api.trafficlight.getProgram(name),
        next_switch=api.trafficlight.getNextSwitch(name)) for name in sorted(api.trafficlight.getIDList())}
    return dict(time=api.simulation.getTime(), vehicles=vehicles, registered_routes=registered,
        missing_registered=missing, tls=lights,
        edge_counts=[api.edge.getLastStepVehicleNumber(edge) for edge in session.network.edge_ids],
        edge_speeds=[api.edge.getLastStepMeanSpeed(edge) for edge in session.network.edge_ids],
        teleports=[list(api.simulation.getStartingTeleportIDList()), list(api.simulation.getEndingTeleportIDList())])


def save_sumo(session, path):
    session._connection.simulation.saveState(str(path))
    raw = gzip.open(path, 'rb').read() if str(path).endswith('.gz') else Path(path).read_bytes()
    root = ET.fromstring(raw)
    if not any('rng' in element.tag.lower() for element in root.iter()):
        raise ValueError('SUMO snapshot does not contain RNG state')
    return hashlib.sha256(ET.tostring(root)).hexdigest()


@dataclass
class BranchSnapshot:
    path: Path
    session: dict
    controller: dict
    external_rng: dict
    demand: dict
    observation: dict
    sumo_sha256: str
    causal_sha256: str


def capture_state(session, controller, path, *, demand):
    if session.backend != 'libsumo' or session.traffic_model != 'meso':
        raise ValueError('initial state-restoration admission is limited to the pretrained libsumo meso contract')
    if session._invalid or session._closed or session._time_ms % 30000:
        raise ValueError('capture requires a valid open macro boundary, outside advance_window callbacks')
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    observation = simulator_observation(session)
    if observation['missing_registered'] or any(observation['teleports']):
        raise ValueError('capture has missing registered vehicles or teleports')
    return BranchSnapshot(Path(path), copy.deepcopy({key: getattr(session, key) for key in SESSION_FIELDS}),
        controller.state_dict(), external_rng_state(), copy.deepcopy(demand), observation,
        save_sumo(session, path), fingerprint(causal_state(session, controller)))


def restore_state(session, controller, snapshot, *, audit_path):
    """Restore both engines; reject loss of queued vehicles or observable state."""
    print(json.dumps(dict(phase='sumo_load_started', snapshot=str(snapshot.path))), flush=True)
    session._connection.simulation.loadState(str(snapshot.path))
    print(json.dumps(dict(phase='sumo_load_finished')), flush=True)
    return verify_loaded_state(session, controller, snapshot, audit_path=audit_path)


def verify_loaded_state(session, controller, snapshot, *, audit_path):
    for key, value in copy.deepcopy(snapshot.session).items():
        setattr(session, key, value)
    session._started_at = time.monotonic()
    controller.load_state_dict(snapshot.controller)
    restore_external_rng(snapshot.external_rng)
    observation = simulator_observation(session)
    sumo_hash = save_sumo(session, audit_path)
    record = dict(sumo_state_equal=sumo_hash == snapshot.sumo_sha256,
        causal_state_equal=fingerprint(causal_state(session, controller)) == snapshot.causal_sha256,
        observation_equal=fingerprint(observation) == fingerprint(snapshot.observation),
        missing_registered=observation['missing_registered'], expected_sumo_sha256=snapshot.sumo_sha256,
        restored_sumo_sha256=sumo_hash, observed=observation)
    atomic_json(Path(audit_path).with_suffix('.audit.json'), plain(record))
    if not all(record[key] for key in ('sumo_state_equal', 'causal_state_equal', 'observation_equal')):
        raise ValueError('full SUMO/Python state replay gate failed; see retained restoration audit')
    return record


def startup_restore(session, controller, snapshot, *, audit_path):
    """Documented startup loader in a fresh interpreter; no demand reinsertion."""
    if session._connection is not None or session.backend != 'libsumo' or session.traffic_model != 'meso':
        raise ValueError('startup restore requires a fresh libsumo meso session')
    raw = gzip.open(snapshot.path, 'rb').read()
    root = ET.fromstring(raw)
    if hashlib.sha256(ET.tostring(root)).hexdigest() != snapshot.sumo_sha256 or root.attrib.get('type') != 'meso':
        raise ValueError('startup snapshot hash/physics differs from captured state')
    import libsumo
    import traci.constants as tc
    if root.attrib.get('version') != libsumo.__version__:
        raise ValueError('startup snapshot SUMO version differs from installed library')
    binary = shutil.which('sumo') or str(Path(sys.executable).parent/'sumo')
    args = [binary, '--net-file', str(session.prepared_inputs.network_xml), '--step-length', '1',
        '--seed', str(session.config.run.seed+session.episode_index), '--no-step-log', 'true',
        '--duration-log.disable', 'true', '--time-to-teleport', '-1', *session._model_args,
        *session.config.simulation.sumo_extra_args, '--load-state', str(snapshot.path.resolve()),
        '--begin', str(snapshot.session['_time_ms']/1000.)]
    print(json.dumps(dict(phase='sumo_startup_load_started', snapshot=str(snapshot.path))), flush=True)
    libsumo.start(args)
    session._connection, session._tc = libsumo, tc
    print(json.dumps(dict(phase='sumo_startup_load_finished')), flush=True)
    return verify_loaded_state(session, controller, snapshot, audit_path=audit_path)


def intervention_controller(controller, *, target, action, start_time, audit):
    def decide(rows, flow, now):
        decisions = controller(rows, flow, now)
        if now == start_time and action is not None:
            indices = [i for i, row in enumerate(rows) if row['vehicle_id'] == target['vehicle_id']]
            if len(indices) != 1:
                raise ValueError('intervention target is not uniquely pending at the captured boundary')
            i = indices[0]
            current, destination = int(rows[i]['current_edge']), int(rows[i]['destination_edge'])
            legal = controller.candidates.candidates(current, destination)
            if current != target['current_edge'] or action not in legal:
                raise ValueError('initial intervention violates captured route legality')
            audit.append(dict(vehicle_id=target['vehicle_id'], time=now, legal=list(legal),
                before=decisions[i].next_edge, after=action))
            decisions[i] = NextHopDecision(target['vehicle_id'], current, int(action), now)
        return decisions
    return decide


def fixed_cohort_cost(vehicles, cohort, start, end):
    rows = {row['vehicle_id']: row for row in vehicles}
    if not cohort or not set(cohort) <= set(rows):
        raise ValueError('fixed cohort must be nonempty and fully observed')
    if end <= start or any(rows[name]['arrived'] and
            ('arrival_time' not in rows[name] or not start <= rows[name]['arrival_time'] <= end) for name in cohort):
        raise ValueError('cohort arrival must have an observed timestamp inside the branch horizon')
    seconds = sum(float(rows[name]['arrival_time']) - start if rows[name]['arrived'] else end-start for name in cohort)
    arrivals = sum(rows[name]['arrived'] for name in cohort)
    return dict(vehicle_seconds=seconds, mean_minutes=seconds / len(cohort) / 60.,
        cohort_size=len(cohort), arrivals=arrivals,
        censored_remaining_time=arrivals < len(cohort), timeout_penalty=0.)


def real_branch(session, controller, snapshot, *, horizon, target=None, action=None):
    start = snapshot.session['_time_ms']/1000.
    cohort = sorted(snapshot.session['_active'])
    trace, interventions = [], []
    decide = intervention_controller(controller, target=target, action=action, start_time=start, audit=interventions)
    for _ in range(horizon//30):
        controller.prepare(session._flow(), session._time_ms/1000.)
        result = session.advance_window(decide)
        counts = np.bincount([row['current_edge'] for row in result.next_state['vehicles']
            if row['vehicle_id'] in cohort and not row['arrived'] and not row.get('in_junction', False)],
            minlength=session.network.edge_count)
        trace.append(dict(time=result.end_time, decisions=[asdict(row) for row in result.decisions],
            vehicles=copy.deepcopy(result.next_state['vehicles']), cohort_counts=counts.tolist(),
            observation=simulator_observation(session)))
    if action is not None and len(interventions) != 1:
        raise ValueError('branch did not execute exactly one declared intervention')
    result = fixed_cohort_cost(trace[-1]['vehicles'], cohort, start, start+horizon)
    return dict(result, action=action, intervention=interventions, trace=trace,
        causal_final_sha256=fingerprint(causal_state(session, controller)))


def prove_self_control(session, controller, snapshot, *, horizon, output):
    reference = real_branch(session, controller, snapshot, horizon=horizon)
    atomic_json(output/'reference.json', plain(reference))
    restore_state(session, controller, snapshot, audit_path=output/'restored.xml.gz')
    replay = real_branch(session, controller, snapshot, horizon=horizon)
    atomic_json(output/'replayed.json', plain(replay))
    if fingerprint(reference) != fingerprint(replay):
        raise ValueError('no-intervention replay trace differs; action comparisons are blocked')
    return dict(exact_trace_equal=True, trace_sha256=fingerprint(reference),
        horizon_seconds=horizon, microstate_restore_proven=True)


def prefix_branch(config, prepared, topology, snapshot, *, prefix_rng, horizon, output, target=None, action=None):
    """Distinct fallback protocol: re-execute the complete registered-demand prefix."""
    restore_external_rng(prefix_rng)
    with SumoEventSession(config, prepared, topology, backend='libsumo') as session:
        session.reset()
        controller = CausalShortestController(topology.network, session.candidates, config.simulation.vehicle_max_speed_mps)
        while session._time_ms < snapshot.session['_time_ms']:
            controller.prepare(session._flow(), session._time_ms/1000.)
            session.advance_window(controller)
        controller.prepare(session._flow(), session._time_ms/1000.)
        actual = capture_state(session, controller, output.with_suffix('.xml.gz'), demand=snapshot.demand)
        checks = dict(method='paired_complete_demand_prefix_replay', microstate_restore_proven=False,
            sumo_state_equal=actual.sumo_sha256 == snapshot.sumo_sha256,
            python_controller_rng_equal=actual.causal_sha256 == snapshot.causal_sha256,
            observation_equal=fingerprint(actual.observation) == fingerprint(snapshot.observation))
        atomic_json(output.with_suffix('.boundary.json'), checks)
        if not all(checks[name] for name in ('sumo_state_equal', 'python_controller_rng_equal', 'observation_equal')):
            raise ValueError('paired prefix failed exact intervention-boundary equality')
        result = real_branch(session, controller, snapshot, horizon=horizon, target=target, action=action)
        atomic_json(output.with_suffix('.json'), plain(result))
        return result


def model_branch(model, snapshot, topology, controls, *, horizon, target, action, mode, draw_seed, steps,
                 executor_seed=0):
    if mode not in ('sampled_prior_fm', 'zero_noise_prior_fm'):
        raise ValueError('unsupported model interpretation; zero-noise FM is not regression')
    network = topology.network
    device = next(model.parameters()).device
    candidates = NextHopCandidates(network, traffic_model='meso')
    controller = CausalShortestController(network, candidates, 40.)
    states = [copy.deepcopy(row) for row in snapshot.session['_vehicles'].values() if row['departed'] and not row['arrived']]
    start = snapshot.session['_time_ms']/1000.
    flow = snapshot.session['_flow_cache'][1]
    generator = torch.Generator(device='cpu').manual_seed(draw_seed)
    arbiter = ChronologicalJunctionArbiter(controls, seed=executor_seed, uncertain_order=True)
    interventions, windows = [], []
    decide = intervention_controller(controller, target=target, action=action, start_time=start, audit=interventions)
    with torch.inference_mode():
        latent = model.encode(torch.as_tensor(flow, dtype=torch.float32, device=device).unsqueeze(0))
        for index in range(horizon//30):
            now = start + 30*index
            decoded = model.decode(latent)[0].cpu().numpy()
            controller.prepare(decoded, now)
            speed = np.minimum(clip_road_speed_fractions(decoded[:, 1], 'meso')*network.speed_limits_mps, 40.)
            physical = advance_city_imagined_window(states, candidates=candidates, edge_speeds_mps=speed,
                frozen_flow=decoded, start_time=now, total_vehicle_count=len(snapshot.session['_vehicles']), decide=decide,
                junction_arbiter=arbiter, interval_seconds=30., observation_step_seconds=1.,
                session_protocol='event', traffic_model='meso', vehicle_max_speed_mps=40., stop_when_empty=False)
            # These are generated in this branch; no factual future action inputs.
            events = pack_action_events([[physical.action_events]], window_starts=[[now]])
            noise = torch.zeros((1, model.dynamics.graph_prior.rank, 64))
            if mode == 'sampled_prior_fm':
                noise = torch.randn(noise.shape, generator=generator)
            latent = model.transition(latent, torch.as_tensor(physical.action, device=device).unsqueeze(0),
                action_events=events.to(device), noise=noise.to(device), steps=steps, solver='euler')
            counts = np.bincount([int(row['current_edge']) for row in states if not row['arrived']], minlength=network.edge_count)
            windows.append(dict(time=physical.end_time, vehicle_seconds=physical.active_vehicle_seconds,
                cohort_counts=counts.tolist(), own_action_events=[asdict(event) for event in physical.action_events]))
    seconds = sum(row['vehicle_seconds'] for row in windows)
    if len(interventions) != 1:
        raise ValueError('model branch did not execute exactly one initial intervention')
    return dict(action=action, mode=mode, draw_seed=draw_seed, vehicle_seconds=seconds,
        mean_minutes=seconds/len(states)/60., windows=windows, intervention=interventions)


def finite_action_assessment(real_costs, predicted_costs):
    if not real_costs or set(real_costs) != set(predicted_costs):
        raise ValueError('ranking requires the same complete finite action set')
    if not all(math.isfinite(v) for costs in (real_costs, predicted_costs) for v in costs.values()):
        raise ValueError('ranking costs must be finite; retain failed arms without a ranking')
    real_best = min(real_costs, key=lambda key: (real_costs[key], key))
    selected = min(predicted_costs, key=lambda key: (predicted_costs[key], key))
    errors = {key: predicted_costs[key]-real_costs[key] for key in real_costs}
    return dict(real_best=real_best, selected=selected, regret_minutes=real_costs[selected]-real_costs[real_best],
        real_rank_groups=rank_groups(real_costs), predicted_rank_groups=rank_groups(predicted_costs),
        signed_bias_minutes=errors, absolute_error_minutes={key: abs(value) for key, value in errors.items()},
        mean_signed_bias_minutes=float(np.mean(list(errors.values()))),
        mean_absolute_error_minutes=float(np.mean([abs(value) for value in errors.values()])),
        operational_selection_tie_break='lowest edge index only; rank groups preserve exact cost ties',
        finite_action_set_only=True)


def rank_groups(costs):
    groups = []
    for action in sorted(costs, key=lambda key: (costs[key], key)):
        if not groups or costs[action] != costs[groups[-1][0]]:
            groups.append([])
        groups[-1].append(action)
    return groups


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--campaign', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--stage', choices=('restore-proof', 'real-ranking', 'ranking'), default='restore-proof')
