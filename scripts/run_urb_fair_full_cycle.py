def main(argv: Iterable[str] | None = None) -> int:
    args = parse_args(argv)
    plan = build_plan(args)
    write_plan_settings(args, plan)
    if args.dry_run:
        print(json.dumps(plan.to_jsonable(), indent=2))
        return 0
    execute_plan(args, plan)
    return 0


