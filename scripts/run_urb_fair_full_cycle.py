def _resolve(path: str | Path, *, base: Path = REPO_ROOT) -> Path:
    value = Path(path).expanduser()
    if value.is_absolute():
        return value.resolve()
    return (base / value).resolve()


def _default_od_file(network_dir: Path, network_name: str) -> Path:
    exact = network_dir / f"od_{network_name}.txt"
    if exact.exists():
        return exact.resolve()
    candidates = sorted(network_dir.glob("od_*.txt"))
    return candidates[0].resolve() if candidates else exact.resolve()


def _count_agents(agents_csv: Path) -> int:
    if not agents_csv.exists():
        return 0
    with agents_csv.open("r", encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        next(reader, None)
        return sum(1 for row in reader if row)


def derive_agent_counts(agents_csv: Path, ratio_machines: float, n_av: int = 0, n_hdv: int = 0) -> tuple[int, int]:
    if n_av > 0 and n_hdv > 0:
        return int(n_av), int(n_hdv)
    n_agents = _count_agents(agents_csv)
    if n_agents <= 0:
        return int(n_av or 30), int(n_hdv or 70)
    derived_av = int(n_agents * float(ratio_machines))
    return int(n_av or derived_av), int(n_hdv or (n_agents - derived_av))


def parse_checkpoint_episodes(raw: str | Sequence[int]) -> list[int]:
    if isinstance(raw, str):
        pieces = [item for item in raw.replace(",", " ").split() if item]
    else:
        pieces = [str(item) for item in raw]
    episodes = [int(item) for item in pieces]
    if not episodes:
        raise ValueError("At least one checkpoint episode is required")
    return episodes


def _quote_env(value: object) -> str:
    text = str(value)
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _write_settings(path: Path, values: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Auto-generated by scripts/run_urb_fair_full_cycle.py.",
        "# Edit command-line arguments instead of editing this file directly.",
    ]
    lines.extend(f"{key}={_quote_env(value)}" for key, value in values.items())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _default_incident_edge(args: argparse.Namespace) -> str:
    for key in (str(args.network_name or ""), Path(str(args.network_dir or "")).name):
        edge = DEFAULT_INCIDENTS.get(key)
        if edge:
            return edge
    return ""


def apply_incident_defaults(args: argparse.Namespace) -> None:
    incident_edge_arg = args.incident_edge
    default_edge = _default_incident_edge(args)
    if incident_edge_arg is None:
        args.incident_edge = default_edge
    else:
        args.incident_edge = str(incident_edge_arg).strip()

    if args.incident_start is None:
        args.incident_start = DEFAULT_INCIDENT_START
    if args.incident_end is None:
        args.incident_end = DEFAULT_INCIDENT_END
    if args.incident_speed is None:
        args.incident_speed = DEFAULT_INCIDENT_SPEED

    incident_enabled = (
        bool(str(args.incident_edge or "").strip())
        and float(args.incident_end) > float(args.incident_start)
        and float(args.incident_speed) > 0.0
    )
    if bool(args.require_incident) and not incident_enabled:
        known = ", ".join(sorted(DEFAULT_INCIDENTS))
        raise ValueError(
            "Incident is required by the URB-fair full-cycle mainline, but no valid "
            f"default incident is configured for network_name={args.network_name!r} "
            f"or network_dir={args.network_dir!r}. Known incident defaults: {known}. "
            "Pass --incident-edge explicitly, or pass --no-require-incident for a "
            "deliberate no-incident baseline."
        )


def _has_route_artifact_bundle(path: Path) -> bool:
    return (
        (path / "agents.csv").exists()
        and (path / "routes.csv").exists()
        and (path / "route.rou.xml").exists()
    )


def _effective_route_artifacts_dir(args: argparse.Namespace, paths: dict[str, object]) -> Path:
    route_artifacts_dir = Path(paths["route_artifacts_dir"])
    if args.route_artifacts_dir or _has_route_artifact_bundle(route_artifacts_dir):
        return route_artifacts_dir
    return Path(paths["collect_records_dir"])


def _eval_candidate_source(args: argparse.Namespace) -> str:
    eval_source = str(getattr(args, "eval_candidate_source", "auto") or "auto").strip().lower()
    if eval_source != "auto":
        return eval_source
    route_source = str(args.route_candidate_source or "current_to_dest").strip().lower()
    if route_source == "od_suffix":
        return "od_suffix"
    if route_source == "current_to_dest":
        return "current_shortest_freeflow"
    raise ValueError(f"Unsupported route candidate source: {args.route_candidate_source!r}")


def _wm_candidate_edge_cost_source(args: argparse.Namespace) -> str:
    source = str(getattr(args, "wm_candidate_edge_cost_source", "freeflow") or "freeflow").strip().lower()
    source = {
        "free_flow": "freeflow",
        "free-flow": "freeflow",
        "ff": "freeflow",
    }.get(source, source)
    if source not in {"auto", "freeflow", "bpr_volume", "decoded_speed", "route_head"}:
        raise ValueError(f"Unsupported wm_candidate_edge_cost_source={source!r}")
    return source


