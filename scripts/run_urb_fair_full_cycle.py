def resolve_paths(args: argparse.Namespace) -> dict[str, object]:
    network_dir = _resolve(args.network_dir)
    output_root = _resolve(args.output_root or Path("data") / args.network_name)
    logs_root = _resolve(args.logs_root or Path("logs") / args.network_name)
    results_root = _resolve(args.results_root or Path("results") / args.network_name)
    generated_config_dir = _resolve(args.generated_config_dir or Path(".urbandreamer") / "generated" / args.network_name)
    route_artifacts_dir = _resolve(args.route_artifacts_dir or network_dir)
    collect_task_name = args.collect_task_name or f"{args.network_name}_urb_fair_eval_postmutation"
    collect_output_dir = _resolve(args.collect_output_dir or output_root / "collect_urb_fair_eval_postmutation")
    collect_records_dir = _resolve(args.collect_records_dir or results_root / "collect_urb_fair_eval_postmutation_records")
    wm_ckpt_dir = _resolve(args.wm_ckpt_dir or logs_root / "dynamics_urb_fair_mainline_8k")
    marl_ckpt_dir = _resolve(args.marl_ckpt_dir or logs_root / "marl_urb_fair_mainline_500ep")
    eval_results_dir = _resolve(args.eval_results_dir or results_root / "eval_urb_fair_mainline_sweep")

    return {
        "network_dir": network_dir,
        "edge_registry": _resolve(args.edge_registry or network_dir / "edge_registry.json"),
        "agents_csv": _resolve(args.agents_csv or network_dir / "agents.csv"),
        "od_file": _resolve(args.od_file or _default_od_file(network_dir, args.network_name)),
        "route_registry": _resolve(args.route_registry or network_dir / "route_registry.json"),
        "route_artifacts_dir": route_artifacts_dir,
        "output_root": output_root,
        "logs_root": logs_root,
        "results_root": results_root,
        "generated_config_dir": generated_config_dir,
        "collect_output_dir": collect_output_dir,
        "collect_records_dir": collect_records_dir,
        "collect_task_name": collect_task_name,
        "wm_ckpt_dir": wm_ckpt_dir,
        "projector_ckpt": wm_ckpt_dir / "flow_projector_latest.pt",
        "dynamics_ckpt": wm_ckpt_dir / "latest.pt",
        "marl_ckpt_dir": marl_ckpt_dir,
        "eval_results_dir": eval_results_dir,
        "best_selection_json": eval_results_dir / "best_checkpoint_selection.json",
        "status_file": logs_root / "urb_fair_full_cycle.status.env",
    }


def build_plan(args: argparse.Namespace) -> FullCyclePlan:
    paths = resolve_paths(args)
    return _commands(args, paths, parse_checkpoint_episodes(args.checkpoint_episodes))


def write_plan_settings(args: argparse.Namespace, plan: FullCyclePlan) -> None:
    paths = resolve_paths(args)
    agents_csv = Path(paths["agents_csv"])
    n_av, n_hdv = derive_agent_counts(agents_csv, args.ratio_machines, args.n_av, args.n_hdv)
    base = _base_settings(args, paths, n_av, n_hdv)
    _write_settings(plan.collect_settings, base)
    _write_settings(plan.dynamics_settings, base)
    _write_settings(plan.marl_settings, base)
    _write_settings(plan.eval_settings, base)


def _write_status(path: Path, stage: str, state: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"STAGE='{stage}'\nSTATE='{state}'\n",
        encoding="utf-8",
    )


def _run(command: Sequence[str], env: dict[str, str]) -> None:
    print("+ " + " ".join(command), flush=True)
    subprocess.run(command, cwd=str(REPO_ROOT), env=env, check=True)


def _bootstrap_route_artifacts(args: argparse.Namespace, paths: dict[str, object], env: dict[str, str]) -> None:
    route_artifacts_dir = _effective_route_artifacts_dir(args, paths)
    if _has_route_artifact_bundle(route_artifacts_dir):
        return

    route_artifacts_dir.mkdir(parents=True, exist_ok=True)
    od_data = load_od_data(str(paths["network_dir"]), args.network_name)
    agents_df = load_agents_dataframe(str(paths["network_dir"]))
    num_agents, _num_machines, max_start_time = compute_agent_counts(agents_df, float(args.ratio_machines))
    ensure_agents_csv_in_records(str(paths["network_dir"]), str(route_artifacts_dir), overwrite=True)
    if str(args.route_generator).strip().lower() == "routerl":
        generate_routerl_routes(
            network_folder=str(paths["network_dir"]),
            network_name=args.network_name,
            origins=od_data["origins"],
            destinations=od_data["destinations"],
            n_routes=int(args.n_routes),
            records_folder=str(route_artifacts_dir),
            simulation_timesteps=int(max_start_time) + int(args.sim_buffer_after_last_depart),
            num_agents=int(num_agents),
            beta=float(args.path_gen_beta),
            num_samples=int(args.path_num_samples),
        )
    else:
        generate_dijkstra_routes(
            network_folder=str(paths["network_dir"]),
            network_name=args.network_name,
            origins=od_data["origins"],
            destinations=od_data["destinations"],
            n_routes=int(args.n_routes),
            records_folder=str(route_artifacts_dir),
        )
    if not _has_route_artifact_bundle(route_artifacts_dir):
        raise FileNotFoundError(f"Failed to bootstrap route artifacts in {route_artifacts_dir}")


def execute_plan(args: argparse.Namespace, plan: FullCyclePlan) -> None:
    env = os.environ.copy()
    env.setdefault("WANDB_MODE", "offline")
    if args.sumo_home:
        env["SUMO_HOME"] = args.sumo_home
    paths = resolve_paths(args)

    _bootstrap_route_artifacts(args, paths, env)

    stage_order = {
        "collect": 0,
        "train_dynamics": 1,
        "train_marl": 2,
        "eval": 3,
    }
    start_stage = str(getattr(args, "start_stage", "collect") or "collect")
    start_idx = int(stage_order[start_stage])

    if start_idx <= stage_order["collect"]:
        _write_status(plan.status_file, "collect_urb_fair", "running")
        _run(plan.collect_command, env)
    if start_idx <= stage_order["train_dynamics"]:
        _write_status(plan.status_file, "train_dynamics", "running")
        _run(plan.dynamics_command, env)
    if start_idx <= stage_order["train_marl"]:
        _write_status(plan.status_file, "train_marl", "running")
        _run(plan.marl_command, env)

    _write_status(plan.status_file, "eval_urb_fair", "running")

    produced_eval_dirs: list[Path] = []
    for command, out_dir in zip(plan.eval_commands, plan.eval_dirs):
        ckpt_path = Path(command[command.index("--policy_ckpt") + 1])
        if not ckpt_path.exists():
            print(f"[warn] Missing checkpoint, skip SUMO probe: {ckpt_path}", file=sys.stderr)
            continue
        _run(command, env)
        produced_eval_dirs.append(out_dir)

    if not produced_eval_dirs:
        raise RuntimeError("No SUMO eval probe directories were produced.")

    select_command = [
        *plan.select_best_command[:3],
        str(plan.select_best_command[3]),
        *[str(path) for path in produced_eval_dirs],
    ]
    _run(select_command, env)
    _write_status(plan.status_file, "complete", "succeeded")


