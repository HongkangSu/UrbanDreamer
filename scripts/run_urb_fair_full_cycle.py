@dataclass(frozen=True)
class FullCyclePlan:
    collect_settings: Path
    dynamics_settings: Path
    marl_settings: Path
    eval_settings: Path
    collect_command: list[str]
    dynamics_command: list[str]
    marl_command: list[str]
    eval_commands: list[list[str]]
    eval_dirs: list[Path]
    select_best_command: list[str]
    status_file: Path

    def to_jsonable(self) -> dict:
        return {
            "settings": {
                "collect": str(self.collect_settings),
                "dynamics": str(self.dynamics_settings),
                "marl": str(self.marl_settings),
                "eval": str(self.eval_settings),
            },
            "commands": {
                "collect": self.collect_command,
                "dynamics": self.dynamics_command,
                "marl": self.marl_command,
                "eval": self.eval_commands,
                "select_best": self.select_best_command,
            },
            "eval_dirs": [str(path) for path in self.eval_dirs],
            "status_file": str(self.status_file),
        }


def _resolve(path: str | Path, *, base: Path = REPO_ROOT) -> Path:
    value = Path(path).expanduser()
    if value.is_absolute():
        return value.resolve()
    return (base / value).resolve()


def _default_od_file(network_dir: Path, network_name: str) -> Path:
    exact = network_dir / f"od_{network_name}.txt"
    if exact.exists():
        return exact.resolve()
    candidates = sorted(network_dir.glob("od_*.txt"))
    return candidates[0].resolve() if candidates else exact.resolve()


def _count_agents(agents_csv: Path) -> int:
    if not agents_csv.exists():
        return 0
    with agents_csv.open("r", encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        next(reader, None)
        return sum(1 for row in reader if row)


def derive_agent_counts(agents_csv: Path, ratio_machines: float, n_av: int = 0, n_hdv: int = 0) -> tuple[int, int]:
    if n_av > 0 and n_hdv > 0:
        return int(n_av), int(n_hdv)
    n_agents = _count_agents(agents_csv)
    if n_agents <= 0:
        return int(n_av or 30), int(n_hdv or 70)
    derived_av = int(n_agents * float(ratio_machines))
    return int(n_av or derived_av), int(n_hdv or (n_agents - derived_av))


def parse_checkpoint_episodes(raw: str | Sequence[int]) -> list[int]:
    if isinstance(raw, str):
        pieces = [item for item in raw.replace(",", " ").split() if item]
    else:
        pieces = [str(item) for item in raw]
    episodes = [int(item) for item in pieces]
    if not episodes:
        raise ValueError("At least one checkpoint episode is required")
    return episodes


def _quote_env(value: object) -> str:
    text = str(value)
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _write_settings(path: Path, values: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Auto-generated by scripts/run_urb_fair_full_cycle.py.",
        "# Edit command-line arguments instead of editing this file directly.",
    ]
    lines.extend(f"{key}={_quote_env(value)}" for key, value in values.items())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _has_route_artifact_bundle(path: Path) -> bool:
    return (
        (path / "agents.csv").exists()
        and (path / "routes.csv").exists()
        and (path / "route.rou.xml").exists()
    )


def _effective_route_artifacts_dir(args: argparse.Namespace, paths: dict[str, object]) -> Path:
    route_artifacts_dir = Path(paths["route_artifacts_dir"])
    if args.route_artifacts_dir or _has_route_artifact_bundle(route_artifacts_dir):
        return route_artifacts_dir
    return Path(paths["collect_records_dir"])


